import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../../package.json', import.meta.url));
const { chromium } = require('playwright-core');
const C = JSON.parse(fs.readFileSync('canvis.json', 'utf8'));
const frases = Object.entries({ ...C.david, ...C.claude }).map(([id, text]) => ({ id, text, autor: C.david[id] ? 'david' : 'claude' }));
const sits = C.canviades.map(id => ({ id, ...C.U[id] }));
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const pg = await b.newPage({ viewport: { width: 1200, height: 900 } });
const errs = []; pg.on('pageerror', e => errs.push(String(e)));
await pg.addInitScript(([frases, sits]) => {
  const docs = { frases: frases.map(f => ({ id: f.id, data: () => ({ text: f.text, autor: f.autor, nova: false }) })), situacions: sits.map(s => ({ id: s.id, data: () => s })) };
  const col = name => ({ doc: () => ({ set: async () => {}, get: async () => ({ exists: false }) }), onSnapshot: ok => { setTimeout(() => ok({ docs: docs[name] || [] }), 10); return () => {}; } });
  window.claude = { use: async k => (k === 'db' ? { collection: col, doc: () => ({ set: async () => {}, get: async () => ({ exists: false }), onSnapshot: () => () => {} }) } : null) };
}, [frases, sits]);
await pg.goto(new URL('./index.html', import.meta.url).href);
await pg.waitForTimeout(500);
const out = await pg.evaluate(() => [...document.querySelectorAll('#sits .card')].map(c => c.id.slice(2) + '\n' + [...c.querySelectorAll('.fr')].map(f => '  ' + (f.dataset.rol === 'bona' ? 'B ' : 'D ') + f.querySelector('.prev').textContent.replace("L'alumne veu: ", '') + (f.querySelector('.warn').textContent ? '   ⚠ ' + f.querySelector('.warn').textContent : '')).join('\n')).join('\n'));
console.log(out);
console.log('marks:', await pg.evaluate(() => document.querySelectorAll('#sits .prev mark').length), 'errors:', errs, await pg.textContent('#cnt'));
await pg.evaluate(() => document.querySelector('#s-DSIG1').scrollIntoView());
await pg.screenshot({ path: 'cap-dsig1.png' });
await b.close();
